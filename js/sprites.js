  function expand(def) {
    if (def._rows) return def._rows;
    let rows;
    if (def.base) {
      const b = expand(S[def.base]);
      const sw = def.swap || {};
      rows = b.map((r) => r.split('').map((ch) => (sw[ch] !== undefined ? sw[ch] : ch)).join(''));
    } else if (def.m) {
      rows = def.rows.map((r) => r + r.split('').reverse().join(''));
    } else rows = def.rows.slice();
    const w = Math.max(...rows.map((r) => r.length));
    rows = rows.map((r) => r.padEnd(w, '.'));
    def._rows = rows;
    return rows;
  }

  // per-sprite palettes (the HD heroes bring their own soft colours)
  function palOf(d) {
    if (d._pal) return d._pal;
    const own = d.pal || (d.base && S[d.base] && S[d.base].pal);
    return (d._pal = own ? Object.assign({}, PAL, own) : PAL);
  }
  G.SPR = S;
  G.PAL = PAL;
  // HD sprites have about twice the pixels, so they are drawn at about half the scale
  G.sprScale = (name, scale) => { const d = S[name]; if (!d || !d.hd || scale < 2) return scale; return d.hdk ? scale * d.hdk : Math.max(1, Math.round(scale * 0.55)); };
  G.sprSize = (name) => {
    const d = S[name];
    if (!d) return { w: 16, h: 16 };
    const r = expand(d);
    return { w: r[0].length, h: r.length };
  };

  const cache = {};
  // returns dataURL of sprite at 1x (scale with CSS)
  G.sprURL = (name, opts) => {
    opts = opts || {};
    const key = name + '|' + (opts.swap ? JSON.stringify(opts.swap) : '') + '|' + (opts.flip ? 1 : 0) + '|' + (opts.sil || '');
    if (cache[key]) return cache[key];
    const d = S[name];
    if (!d || typeof document === 'undefined') return '';
    const rows = expand(d);
    const P = palOf(d);
    const h = rows.length, w = rows[0].length;
    const cv = document.createElement('canvas');
    cv.width = w; cv.height = h;
    const ctx = cv.getContext('2d');
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        let ch = rows[y][opts.flip ? w - 1 - x : x];
        if (ch === '.' || ch === ' ') continue;
        if (opts.swap && opts.swap[ch] !== undefined) ch = opts.swap[ch];
        ctx.fillStyle = opts.sil || P[ch] || '#f0f';
        ctx.fillRect(x, y, 1, 1);
      }
    }
    return (cache[key] = cv.toDataURL());
  };

  // 1x offscreen canvas of a sprite (for drawing onto other canvases)
  const cvCache = {};
  G.sprCanvas = (name, flip) => {
    if (S[name + '_mini']) name += '_mini';
    const key = name + (flip ? '|f' : '');
    if (cvCache[key]) return cvCache[key];
    const d = S[name];
    if (!d || typeof document === 'undefined') return null;
    const rows = expand(d);
    const cv = document.createElement('canvas');
    cv.width = rows[0].length; cv.height = rows.length;
    const ctx = cv.getContext('2d');
    for (let y = 0; y < rows.length; y++) {
      for (let x = 0; x < cv.width; x++) {
        const ch = rows[y][flip ? cv.width - 1 - x : x];
        if (ch === '.' || ch === ' ') continue;
        ctx.fillStyle = palOf(d)[ch] || '#f0f';
        ctx.fillRect(x, y, 1, 1);
      }
    }
    return (cvCache[key] = cv);
  };

  // <img> element of sprite scaled
  G.sprImg = (name, scale, opts) => {
    const sz = G.sprSize(name);
    const img = document.createElement('img');
    img.src = G.sprURL(name, opts);
    img.className = 'px';
    scale = G.sprScale(name, scale);
    img.width = sz.w * scale;
    img.height = sz.h * scale;
    img.draggable = false;
    return img;
  };
